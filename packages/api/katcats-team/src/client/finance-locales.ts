/** Dictionary keys for localized financial connection UI. */
export type FinanceKey = keyof typeof financeZh

/** Safe errors displayed in a connector workflow. */
export type FinanceErrorKey = Extract<FinanceKey, `error.${string}`>

/**
 * Resolve a declared failure into its localized recovery label.
 * @param reason - failure classified by the connector host.
 * @returns the locale-owned recovery message key.
 */
export function financeFailureKey(reason: FinanceFailureReason): FinanceErrorKey {
  return `error.${reason}`
}

/**
 * Choose ledger setup copy when a finance failure has a different cause in setup.
 * @param key - The localized error reported by the connector.
 * @returns The message key appropriate for a ledger setup operation.
 */
export function ledgerSetupErrorKey(key: FinanceKey): FinanceKey {
  if (key === 'error.permissions') return 'setup.error.permissions'
  if (key === 'error.invalid-input') return 'setup.error.invalid-input'
  if (key === 'error.ledger-mismatch') return 'setup.error.mismatch'
  if (key === 'error.ledger-unverified') return 'setup.error.unverified'
  return key
}

